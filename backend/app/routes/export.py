router = APIRouter(prefix="/export", tags=["Export"])

@router.get("/predictions-csv")
def export_predictions_csv(
    request: Request,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    csv_path = "test_predictions.csv"
    if not os.path.exists(csv_path):
        # Fallback to local directory
        csv_path = os.path.join(os.getcwd(), "test_predictions.csv")

    log_event(
        db=db,
        action="export:predictions_csv",
        user=current_user,
        resource_type="export",
        request=request
    )

    if os.path.exists(csv_path):
        def iter_file():
            with open(csv_path, mode="rb") as f:
                yield from f
        return StreamingResponse(
            iter_file(),
            media_type="text/csv",
            headers={"Content-Disposition": 'attachment; filename="shelf_signal_test_predictions.csv"'}
        )

    # Generate sample CSV if file doesn't exist
    content = "store_num,upc,week_end_date,units,pred\n367,1111009477,2011-07-20,42,40.8\n367,1111009497,2011-07-20,18,19.2\n"
    return Response(
        content=content,
        media_type="text/csv",
        headers={"Content-Disposition": 'attachment; filename="shelf_signal_test_predictions.csv"'}
    )

